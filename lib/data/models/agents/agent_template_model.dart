class AgentTemplateModel {
  final String id;
  final String title;
  final String category;
  final String description;
  final String language;
  final String personaVoice;
  final String callLimit;
  final String useCase;
  final int usedTokens;
  final int maxTokens;
  final String samplePrompt;
  final String systemPrompt;

  const AgentTemplateModel({
    required this.id,
    required this.title,
    required this.category,
    required this.description,
    required this.language,
    required this.personaVoice,
    required this.callLimit,
    required this.useCase,
    required this.usedTokens,
    this.maxTokens = 800,
    required this.samplePrompt,
    required this.systemPrompt,
  });

  factory AgentTemplateModel.fromJson(Map<String, dynamic> json) {
    return AgentTemplateModel(
      id: json['id'] as String,
      title: json['title'] as String,
      category: json['category'] as String,
      description: json['description'] as String,
      language: json['language'] as String? ?? 'English (India)',
      personaVoice: json['persona_voice'] as String? ?? 'Riya - Female actor',
      callLimit: json['call_limit'] as String? ?? '3 minutes',
      useCase: json['use_case'] as String,
      usedTokens: json['used_tokens'] as int? ?? 400,
      maxTokens: json['max_tokens'] as int? ?? 800,
      samplePrompt: json['sample_prompt'] as String,
      systemPrompt: json['system_prompt'] as String,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'title': title,
      'category': category,
      'description': description,
      'language': language,
      'persona_voice': personaVoice,
      'call_limit': callLimit,
      'use_case': useCase,
      'used_tokens': usedTokens,
      'max_tokens': maxTokens,
      'sample_prompt': samplePrompt,
      'system_prompt': systemPrompt,
    };
  }
}

